export function getDealRating(vehicle: Pick<Vehicle, 'price' | 'fairMarketPrice'>): {
  rating: DealRating;
  savings: number;
  savingsPct: number;
} {
  const savings = vehicle.fairMarketPrice - vehicle.price;
  const savingsPct = vehicle.fairMarketPrice > 0 ? (savings / vehicle.fairMarketPrice) * 100 : 0;
  if (savingsPct >= 4.2 || savings >= 3500) {
    return { rating: 'Great Deal', savings, savingsPct };
  }
  if (savingsPct >= 2.0 || savings >= 1400) {
    return { rating: 'Good Deal', savings, savingsPct };
  }
  return { rating: 'Fair Price', savings, savingsPct };
}

